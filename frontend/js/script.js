
const prepareScanButton = document.getElementById("prepareScanBtn");

if (prepareScanButton) {
    prepareScanButton.addEventListener("click", () => {
        showPage("detection");
    });
}

const navLinks = document.querySelectorAll(".nav-link");

function showPage(pageName) {
    const dashboardPage = document.getElementById("dashboardPage");
    const detectionPage = document.getElementById("detectionPage");
    const regexPage = document.getElementById("regexPage");
    const historyPage = document.getElementById("historyPage");
    const reportsPage = document.getElementById("reportsPage");

    const pages = {
    dashboard: dashboardPage,
    detection: detectionPage,
    regex: regexPage,
    history: historyPage,
    reports: reportsPage
};

    if (!pages[pageName]) {
        return;
    }

    Object.entries(pages).forEach(([name, page]) => {
        if (page) {
            page.hidden = name !== pageName;
        }
    });

    navLinks.forEach(link => {
        link.classList.toggle(
            "active",
            link.dataset.page === pageName
        );
    });

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

navLinks.forEach(link => {
    link.addEventListener("click", event => {
        const pageName = link.dataset.page;

        if (
            pageName === "dashboard" ||
            pageName === "detection" ||
            pageName === "regex" ||
            pageName === "history"
        ) {
            event.preventDefault();
            showPage(pageName);
        }
    });
    if (window.location.hash === "#regex") {
    showPage("regex");
}
});

function loadDetectionHistory() {
    const historyContainer = document.getElementById("historyContainer");

    if (!historyContainer) {
        return;
    }

    const scanHistory = JSON.parse(
        localStorage.getItem("cyberTraceHistory") || "[]"
    );

    if (scanHistory.length === 0) {
        historyContainer.innerHTML = `
            <div class="history-empty">
                <p>No scan history available yet.</p>
            </div>
        `;
        return;
    }

    historyContainer.innerHTML = scanHistory.map(scan => `
        <div class="history-card">

            <div class="history-card-header">
                <div class="history-file">
                    <div class="history-file-icon">▤</div>
                    <div>
                        <h4>${scan.fileName}</h4>
                        <p class="history-date">${scan.date}</p>
                    </div>
                </div>

                                <div class="history-status ${
                    scan.totalAlerts > 0 ? "has-threats" : "clean"
                }">
                    ${scan.totalAlerts > 0 ? "THREATS DETECTED" : "CLEAN SCAN"}
                </div>

                <button class="download-report-btn"
                    onclick="downloadScanReport(${scanHistory.indexOf(scan)})">
                    Download Report
                </button>
            </div>

            <div class="history-total">
                <span>Total Alerts</span>
                <h2>${scan.totalAlerts}</h2>
            </div>

            <div class="history-breakdown">
                <div class="history-metric">
                    <span>Brute Force</span>
                    <strong>${scan.bruteForce}</strong>
                </div>

                <div class="history-metric">
                    <span>Port Scanning</span>
                    <strong>${scan.portScanning}</strong>
                </div>

                <div class="history-metric">
                    <span>SQL Injection</span>
                    <strong>${scan.sqlInjection}</strong>
                </div>

                <div class="history-metric">
                    <span>XSS</span>
                    <strong>${scan.xss}</strong>
                </div>
            </div>

        </div>
    `).join("");
}

loadDetectionHistory();

function downloadScanReport(index) {
    const scanHistory = JSON.parse(
        localStorage.getItem("cyberTraceHistory") || "[]"
    );

    const scan = scanHistory[index];

    if (!scan) {
        return;
    }

    const report = `
CYBERTRACE - SECURITY SCAN REPORT
=================================

File Name: ${scan.fileName}
Scan Date: ${scan.date}

SCAN SUMMARY
-----------
Total Alerts: ${scan.totalAlerts}

ATTACK BREAKDOWN
----------------
Brute Force: ${scan.bruteForce}
Port Scanning: ${scan.portScanning}
SQL Injection: ${scan.sqlInjection}
XSS: ${scan.xss}

=================================
Generated by CyberTrace
Automata-Based Cyberattack Pattern Detector
`;

    const blob = new Blob([report], {
        type: "text/plain"
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = url;
    link.download = `CyberTrace_Report_${index + 1}.txt`;

    document.body.appendChild(link);
    link.click();
    link.remove();

    URL.revokeObjectURL(url);
}
